/**
 * Générateur pseudo-aléatoire déterministe (pas de `Math.random()` dans le moteur) : même graine,
 * même suite. Partagé par le mode Red/Blue (cyber) et le mode panne (troubleshoot).
 */

/** mulberry32 : générateur seedé, suffisant pour tirer des choix reproductibles. */
export function mulberry32(seed: number): () => number {
  let a = seed >>> 0
  return () => {
    a = (a + 0x6d2b79f5) >>> 0
    let t = a
    t = Math.imul(t ^ (t >>> 15), t | 1)
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

/** Mélange de Fisher-Yates (copie), piloté par `rand`. */
export function shuffle<T>(items: readonly T[], rand: () => number): T[] {
  const out = [...items]
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1))
    ;[out[i], out[j]] = [out[j]!, out[i]!]
  }
  return out
}
